    private val byId = all.associateBy { it.id }
    fun get(id: String): Exercise? = byId[id]
    operator fun invoke(id: String): Exercise = byId[id] ?: error("Unknown exercise $id")

    fun effectiveEquipment(eq: Set<Equipment>): Set<Equipment> =
        if (FULL_GYM in eq) Equipment.entries.toSet() else eq + NONE

    fun available(e: Exercise, eq: Set<Equipment>): Boolean = e.needs.isEmpty() || e.needs.any { it in effectiveEquipment(eq) }
    fun safeFor(e: Exercise, lim: Set<Limitation>): Boolean = e.avoid.none { it in lim }
