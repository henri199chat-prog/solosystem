enum class Muscle(val ar: String, val en: String) {
    QUADS("الفخذ الأمامي", "Quads"), GLUTES("الأرداف", "Glutes"), HAMSTRINGS("الفخذ الخلفي", "Hamstrings"),
    CALVES("السمانة", "Calves"), CHEST("الصدر", "Chest"), SHOULDERS("الأكتاف", "Shoulders"),
    TRICEPS("الترايسبس", "Triceps"), BACK("الظهر العريض", "Lats / back"), UPPER_BACK("أعلى الظهر", "Upper back"),
    BICEPS("البايسبس", "Biceps"), CORE("عضلات الجذع", "Core"), FOREARMS("الساعد", "Forearms"),
    HEART("القلب والتنفس", "Cardio")
}

/** Pose key used by the UI to draw a simple diagram (no fake video). */
enum class Pose { SQUAT, HINGE, LUNGE, PUSHUP, PRESS, ROW, PULLUP, PLANK, BRIDGE, CURL, CARRY, JUMP, WALK, RAISE, HANG, DIP, CORE_FLOOR }

data class Exercise(
    val id: String,
    val ar: String,
    val en: String,
    val pattern: Pattern,
    val level: Int,                       // 1 (easiest) .. 5
    val needs: Set<Equipment> = emptySet(), // any one of these satisfies; empty = bodyweight
    val muscles: List<Muscle>,
    val avoid: Set<Limitation> = emptySet(),
    val cuesAr: List<String>,
    val cuesEn: List<String>,
    val regression: String? = null,
    val progression: String? = null,
    val loadable: Boolean = false,
    val timed: Boolean = false,
    val pose: Pose
) {
    fun name(arabic: Boolean) = if (arabic) ar else en
    fun cues(arabic: Boolean) = if (arabic) cuesAr else cuesEn
}

